"""SimpleElastoDyn standalone driver — reads/writes SED driver input files (.dvr).

Very similar to AeroDisk driver format: right-aligned values and
``@filename.csv`` syntax for timeseries data.
"""
from __future__ import annotations

import os
from pathlib import Path
from typing import Any, Dict

from ..io.simple_elastodyn import SimpleElastoDynIO
from ..parsing import bool_read, float_read, int_read, quoted_read


class SimpleElastoDynStandaloneDriver:
    """Reads and writes SimpleElastoDyn standalone driver input files (.dvr)."""

    def __init__(self) -> None:
        self._sed = SimpleElastoDynIO()

    # ------------------------------------------------------------------
    # READ
    # ------------------------------------------------------------------
    def read(self, dvr_path: Path) -> dict:
        """Read a SimpleElastoDyn driver file and the referenced SED input.

        Returns a dict with keys:
          ``'SimpleElastoDynDriver'`` — driver-level parameters
          ``'SimpleElastoDyn'`` — from SimpleElastoDynIO
        """
        dvr_path = Path(dvr_path)
        base_dir = dvr_path.parent
        dvr: Dict[str, Any] = {}

        with open(dvr_path) as f:
            # --- Header ---
            f.readline()  # title line
            dvr['description'] = f.readline().rstrip()

            # --- Echo ---
            f.readline()  # separator
            dvr['Echo'] = bool_read(f.readline().split()[0])

            # --- Input files ---
            f.readline()  # separator
            dvr['SEDiptFile'] = quoted_read(f.readline().split()[0])
            dvr['OutRootName'] = quoted_read(f.readline().split()[0])

            # --- Output ---
            f.readline()  # section header
            dvr['WrVTK'] = int_read(f.readline().split()[0])

            # --- Case Analysis ---
            f.readline()  # section header
            dvr['TStart'] = float_read(f.readline().split()[0])
            ln = f.readline().split()
            dvr['DT'] = ln[0].strip('"')  # may be "DEFAULT"
            ln = f.readline().split()
            dvr['NumTimeSteps'] = ln[0].strip('"')  # may be "DEFAULT" or int

            # Column headers and units
            f.readline()  # column headers
            f.readline()  # column units

            # Timeseries: either @filename or inline data
            line = f.readline().strip()
            if line.startswith('@'):
                dvr['TimeseriesFile'] = line[1:]
                dvr['TimeseriesData'] = []
            else:
                dvr['TimeseriesFile'] = ''
                rows = []
                while line and not line.upper().startswith('END'):
                    parts = line.split()
                    if parts:
                        rows.append([float_read(p) for p in parts])
                    line = f.readline().strip()
                dvr['TimeseriesData'] = rows

        result: Dict[str, Any] = {'SimpleElastoDynDriver': dvr}

        # --- Delegate to SimpleElastoDynIO ---
        sed_file = dvr.get('SEDiptFile', '')
        sed_path = os.path.normpath(os.path.join(str(base_dir), sed_file))
        if sed_file and os.path.isfile(sed_path):
            sed_data = self._sed.read(Path(sed_path), base_dir)
            result.update(sed_data)

        return result

    # ------------------------------------------------------------------
    # WRITE
    # ------------------------------------------------------------------
    def write(self, data: dict, dvr_path: Path) -> None:
        """Write a SimpleElastoDyn driver file and the referenced SED input."""
        dvr_path = Path(dvr_path)
        base_dir = dvr_path.parent
        dvr = data['SimpleElastoDynDriver']

        with open(dvr_path, 'w') as f:
            f.write('------- SED driver INPUT FILE --------------------------------------------------------------------------------\n')
            f.write(dvr.get('description', 'Generated by OpenFAST_IO') + '\n')
            f.write('--------------------------------------------------------------------------------------------------------------\n')
            f.write('{!s:<35} {:<15} {:}\n'.format(dvr['Echo'], 'Echo', '- Echo input data to <RootName>.ech (flag)'))
            f.write('--------------------------------------------------------------------------------------------------------------\n')

            sed_name = dvr.get('SEDiptFile', 'sed_primary.inp')
            f.write('{:<35} {:<15} {:}\n'.format('"' + sed_name + '"', 'SEDiptFile', '- SED input file'))
            f.write('{:<35} {:<15} {:}\n'.format('"' + dvr.get('OutRootName', 'sed_driver') + '"', 'OutRootName', '- RootName for output files'))
            f.write('----- Output  ------------------------------------------------------------------------------------------------\n')
            f.write('{:<35} {:<15} {:}\n'.format(dvr.get('WrVTK', 0), 'WrVTK', '- Option for writing VTK visualization files [0: none, 1: init only, 2: animation]'))
            f.write('----- Case Analysis ------------------------------------------------------------------------------------------\n')
            f.write('{:<35} {:<15} {:}\n'.format(dvr['TStart'], 'TStart', '- Start time (currently unused)'))
            f.write('{:<35} {:<15} {:}\n'.format('"' + str(dvr['DT']) + '"', 'DT', '- Time step (DEFAULT to use smallest DT from input series)'))
            f.write('{:<35} {:<15} {:}\n'.format(str(dvr['NumTimeSteps']), 'NumTimeSteps', '- Number of timesteps (DEFAULT to run to end of time)'))
            f.write('Time      AerTrq      HSSBrTrqC   GenTrq      BlPitchCom  Yaw         YawRate\n')
            f.write('(s)       (N-m)       (N-m)       (N-m)       (deg)       (deg)       (deg/s)\n')
            ts_file = dvr.get('TimeseriesFile', '')
            if ts_file:
                f.write('@{}\n'.format(ts_file))
            else:
                for row in dvr.get('TimeseriesData', []):
                    f.write('  '.join(str(v) for v in row) + '\n')

        # --- Delegate to SimpleElastoDynIO ---
        if 'SimpleElastoDyn' in data:
            sed_path = os.path.normpath(os.path.join(str(base_dir), sed_name))
            self._sed.write({'SimpleElastoDyn': data['SimpleElastoDyn']}, sed_path, str(base_dir))
