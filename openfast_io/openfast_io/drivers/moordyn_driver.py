"""MoorDyn standalone driver — reads/writes MoorDyn driver input files (.inp).

Handles environmental conditions, MoorDyn input file reference, simulation
timing (TMax/dtC), input modes, and initial position table.
"""
from __future__ import annotations

import os
from pathlib import Path
from typing import Any, Dict, List

from ..io.moordyn import MoorDynIO
from ..parsing import bool_read, float_read, int_read, quoted_read


class MoorDynStandaloneDriver:
    """Reads and writes MoorDyn standalone driver input files (.inp)."""

    def __init__(self) -> None:
        self._moordyn = MoorDynIO()

    # ------------------------------------------------------------------
    # READ
    # ------------------------------------------------------------------
    def read(self, inp_path: Path) -> dict:
        """Read a MoorDyn driver file and the referenced MoorDyn input.

        Returns a dict with keys:
          ``'MoorDynDriver'`` — driver-level parameters
          ``'MoorDyn'`` — from MoorDynIO
        """
        inp_path = Path(inp_path)
        base_dir = inp_path.parent
        dvr: Dict[str, Any] = {}

        with open(inp_path) as f:
            # --- Header ---
            f.readline()  # title line
            f.readline()  # comment line

            # --- Environmental Conditions ---
            f.readline()  # section header
            dvr['Gravity'] = float_read(f.readline().split()[0])
            dvr['rhoW'] = float_read(f.readline().split()[0])
            dvr['WtrDpth'] = float_read(f.readline().split()[0])

            # --- MoorDyn ---
            f.readline()  # section header
            dvr['MDInputFile'] = quoted_read(f.readline().split()[0])
            dvr['OutRootName'] = quoted_read(f.readline().split()[0])
            dvr['TMax'] = float_read(f.readline().split()[0])
            dvr['dtC'] = float_read(f.readline().split()[0])
            dvr['InputsMode'] = int_read(f.readline().split()[0])
            dvr['InputsFile'] = quoted_read(f.readline().split()[0])
            dvr['NumTurbines'] = int_read(f.readline().split()[0])

            # --- Initial Positions ---
            f.readline()  # section header
            f.readline()  # column headers
            f.readline()  # column units
            n_rows = max(1, dvr['NumTurbines'])
            positions: List[Dict[str, float]] = []
            for _ in range(n_rows):
                ln = f.readline().split()
                positions.append({
                    'ref_X': float_read(ln[0]),
                    'ref_Y': float_read(ln[1]),
                    'surge_init': float_read(ln[2]),
                    'sway_init': float_read(ln[3]),
                    'heave_init': float_read(ln[4]),
                    'roll_init': float_read(ln[5]),
                    'pitch_init': float_read(ln[6]),
                    'yaw_init': float_read(ln[7]),
                })
            dvr['InitialPositions'] = positions

        result: Dict[str, Any] = {'MoorDynDriver': dvr}

        # --- Delegate to MoorDynIO ---
        md_file = dvr.get('MDInputFile', '')
        md_path = os.path.normpath(os.path.join(str(base_dir), md_file))
        if md_file and os.path.isfile(md_path):
            md_data = self._moordyn.read(Path(md_path), base_dir)
            result.update(md_data)

        return result

    # ------------------------------------------------------------------
    # WRITE
    # ------------------------------------------------------------------
    def write(self, data: dict, inp_path: Path) -> None:
        """Write a MoorDyn driver file and the referenced MoorDyn input."""
        inp_path = Path(inp_path)
        base_dir = inp_path.parent
        dvr = data['MoorDynDriver']

        with open(inp_path, 'w') as f:
            f.write('MoorDyn driver input file\n')
            f.write('Generated by OpenFAST_IO\n')
            f.write('---------------------- ENVIRONMENTAL CONDITIONS -------------------------------\n')
            f.write('{:<20} {:<17} {:}\n'.format(dvr['Gravity'], 'Gravity', '- Gravity (m/s^2)'))
            f.write('{:<20} {:<17} {:}\n'.format(dvr['rhoW'], 'rhoW', '- Water density (kg/m^3)'))
            f.write('{:<20} {:<17} {:}\n'.format(dvr['WtrDpth'], 'WtrDpth', '- Water depth (m)'))
            f.write('---------------------- MOORDYN ------------------------------------------------\n')

            md_name = dvr.get('MDInputFile', 'moordyn.dat')
            f.write('{:<20} {:<17} {:}\n'.format('"' + md_name + '"', 'MDInputFile', '- Primary MoorDyn input file name (quoted string)'))
            f.write('{:<20} {:<17} {:}\n'.format('"' + dvr.get('OutRootName', 'driver') + '"', 'OutRootName', '- The name which prefixes all MoorDyn generated files (quoted string)'))
            f.write('{:<20} {:<17} {:}\n'.format(dvr['TMax'], 'TMax', '- Total simulation time (s)'))
            f.write('{:<20} {:<17} {:}\n'.format(dvr['dtC'], 'dtC', '- TimeInterval for the simulation (sec)'))
            f.write('{:<20} {:<17} {:}\n'.format(dvr['InputsMode'], 'InputsMode', '- MoorDyn coupled object inputs {0: zero, 1: time-series} (switch)'))
            f.write('{:<20} {:<17} {:}\n'.format('"' + dvr.get('InputsFile', '') + '"', 'InputsFile', '- Filename for the MoorDyn inputs file'))
            f.write('{:<20} {:<17} {:}\n'.format(dvr['NumTurbines'], 'NumTurbines', '- Number of wind turbines (-)'))
            f.write('---------------------- Initial Positions --------------------------------------\n')
            f.write('ref_X    ref_Y    surge_init   sway_init  heave_init  roll_init  pitch_init   yaw_init\n')
            f.write(' (m)      (m)        (m)          (m)        (m)       (deg)       (deg)        (deg)\n')
            for pos in dvr.get('InitialPositions', []):
                f.write('  {:<9} {:<9} {:<13} {:<11} {:<12} {:<11} {:<13} {}\n'.format(
                    pos['ref_X'], pos['ref_Y'], pos['surge_init'], pos['sway_init'],
                    pos['heave_init'], pos['roll_init'], pos['pitch_init'], pos['yaw_init']))
            f.write('END of driver input file\n')

        # --- Delegate to MoorDynIO ---
        if 'MoorDyn' in data:
            md_path = os.path.normpath(os.path.join(str(base_dir), md_name))
            self._moordyn.write({'MoorDyn': data['MoorDyn']}, md_path, str(base_dir))
