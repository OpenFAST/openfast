!----------------------------------------------------------------------------------------------------------------------------------
!> Read and validate user-defined current profile data from an ASCII file.
SUBROUTINE ReadUsrCurrentProfile( CurrFile, CurrentData, ErrStat, ErrMsg )

      IMPLICIT NONE

      CHARACTER(*),                  INTENT(IN   ) :: CurrFile
      TYPE(Current_InitInputType),   INTENT(INOUT) :: CurrentData
      INTEGER(IntKi),                INTENT(  OUT) :: ErrStat
      CHARACTER(*),                  INTENT(  OUT) :: ErrMsg
      INTEGER(IntKi)                               :: UnIn
      INTEGER(IntKi)                               :: IOS
      INTEGER(IntKi)                               :: NRows
      INTEGER(IntKi)                               :: RowIdx
      INTEGER(IntKi)                               :: LineNum
      CHARACTER(1024)                              :: Line
      CHARACTER(1024)                              :: CleanLine
      REAL(SiKi)                                   :: TmpRow(3)
      REAL(SiKi)                                   :: Depth
      REAL(SiKi)                                   :: PrevDepth
      LOGICAL                                      :: DataStarted
      INTEGER(IntKi)                               :: ErrStat2
      CHARACTER(ErrMsgLen)                         :: ErrMsg2
      CHARACTER(*), PARAMETER                      :: RoutineName = 'ReadUsrCurrentProfile'

      ErrStat = ErrID_None
      ErrMsg  = ''

      if (allocated(CurrentData%UsrCurrProfileDepth)) deallocate(CurrentData%UsrCurrProfileDepth)
      if (allocated(CurrentData%UsrCurrProfileVxi  )) deallocate(CurrentData%UsrCurrProfileVxi)
      if (allocated(CurrentData%UsrCurrProfileVyi  )) deallocate(CurrentData%UsrCurrProfileVyi)

      call GetNewUnit( UnIn )
      call OpenFInpFile( UnIn, TRIM(CurrFile), ErrStat2, ErrMsg2 ); if (Failed()) return

      NRows = 0
      LineNum = 0
      DataStarted = .false.
      do
         read( UnIn, '(A)', IOSTAT=IOS ) Line
         LineNum = LineNum + 1
         if ( IOS < 0 ) exit
         if ( IOS /= 0 ) then
            call SetErrStat( ErrID_Fatal, 'Error reading current profile file '//TRIM(CurrFile)//' at line '//TRIM(Num2LStr(LineNum))//'.', ErrStat, ErrMsg, RoutineName )
            call CleanUp()
            return
         end if

         CleanLine = ADJUSTL( Line )
         ErrStat2 = ErrID_None
         ErrMsg2  = ''
         call ReadAry( CleanLine, TmpRow, 3, 'CurrentProfileLine', 'depth, x-velocity, y-velocity', ErrStat2, ErrMsg2 )
         if ( ErrStat2 >= AbortErrLev .or. LEN_TRIM(ErrMsg2) > 0 ) then
            if ( .not. DataStarted ) cycle
            call SetErrStat( ErrID_Fatal, 'Invalid current profile data at line '//TRIM(Num2LStr(LineNum))//' in file '//TRIM(CurrFile)//'. '//TRIM(ErrMsg2), ErrStat, ErrMsg, RoutineName )
            call CleanUp()
            return
         end if

         DataStarted = .true.
         NRows = NRows + 1
      end do

      if ( NRows <= 0 ) then
         call SetErrStat( ErrID_Fatal, 'Current profile file '//TRIM(CurrFile)//' contains no data rows.', ErrStat, ErrMsg, RoutineName )
         call CleanUp()
         return
      end if

      rewind( UnIn, IOSTAT=IOS )
      if ( IOS /= 0 ) then
         call SetErrStat( ErrID_Fatal, 'Error rewinding current profile file '//TRIM(CurrFile)//'.', ErrStat, ErrMsg, RoutineName )
         call CleanUp()
         return
      end if

      call AllocAry( CurrentData%UsrCurrProfileDepth, NRows, 'UsrCurrProfileDepth', ErrStat2, ErrMsg2 ); if (Failed()) return
      call AllocAry( CurrentData%UsrCurrProfileVxi, NRows, 'UsrCurrProfileVxi', ErrStat2, ErrMsg2 ); if (Failed()) return
      call AllocAry( CurrentData%UsrCurrProfileVyi, NRows, 'UsrCurrProfileVyi', ErrStat2, ErrMsg2 ); if (Failed()) return

      RowIdx = 0
      LineNum = 0
      DataStarted = .false.
      PrevDepth = HUGE(PrevDepth)
      do
         read( UnIn, '(A)', IOSTAT=IOS ) Line
         LineNum = LineNum + 1
         if ( IOS < 0 ) exit
         if ( IOS /= 0 ) then
            call SetErrStat( ErrID_Fatal, 'Error reading current profile file '//TRIM(CurrFile)//' at line '//TRIM(Num2LStr(LineNum))//'.', ErrStat, ErrMsg, RoutineName )
            call CleanUp()
            return
         end if

         CleanLine = ADJUSTL( Line )
         ErrStat2 = ErrID_None
         ErrMsg2  = ''
         call ReadAry( CleanLine, TmpRow, 3, 'CurrentProfileLine', 'depth, x-velocity, y-velocity', ErrStat2, ErrMsg2 )
         if ( ErrStat2 >= AbortErrLev .or. LEN_TRIM(ErrMsg2) > 0 ) then
            if ( .not. DataStarted ) cycle
            call SetErrStat( ErrID_Fatal, 'Invalid current profile data at line '//TRIM(Num2LStr(LineNum))//' in file '//TRIM(CurrFile)//'. '//TRIM(ErrMsg2), ErrStat, ErrMsg, RoutineName )
            call CleanUp()
            return
         end if

         DataStarted = .true.
         RowIdx = RowIdx + 1
         Depth = TmpRow(1)

         if ( Depth > 0.0_SiKi ) then
            call SetErrStat( ErrID_Fatal, 'Current profile depth must be non-positive at line '//TRIM(Num2LStr(LineNum))//' in file '//TRIM(CurrFile)//'.', ErrStat, ErrMsg, RoutineName )
            call CleanUp()
            return
         end if

         if ( RowIdx > 1 ) then
            if ( Depth >= PrevDepth ) then
               call SetErrStat( ErrID_Fatal, 'Current profile depths must be strictly decreasing at line '//TRIM(Num2LStr(LineNum))//' in file '//TRIM(CurrFile)//'.', ErrStat, ErrMsg, RoutineName )
               call CleanUp()
               return
            end if
         end if

         CurrentData%UsrCurrProfileDepth(RowIdx) = Depth
         CurrentData%UsrCurrProfileVxi(RowIdx)   = TmpRow(2)
         CurrentData%UsrCurrProfileVyi(RowIdx)   = TmpRow(3)
         PrevDepth = Depth
      end do

      close( UnIn )

contains

   logical function Failed()
      call SetErrStat( ErrStat2, ErrMsg2, ErrStat, ErrMsg, RoutineName )
      Failed = ErrStat >= AbortErrLev
      if (Failed) call CleanUp()
   end function

   subroutine CleanUp
      close( UnIn )
      if (allocated(CurrentData%UsrCurrProfileDepth)) deallocate(CurrentData%UsrCurrProfileDepth)
      if (allocated(CurrentData%UsrCurrProfileVxi  )) deallocate(CurrentData%UsrCurrProfileVxi)
      if (allocated(CurrentData%UsrCurrProfileVyi  )) deallocate(CurrentData%UsrCurrProfileVyi)
   end subroutine CleanUp

END SUBROUTINE ReadUsrCurrentProfile


!----------------------------------------------------------------------------------------------------------------------------------
!> Interpolate the user-defined current profile at a given depth.
SUBROUTINE CurrentProfileAtDepth( QueryDepth, UsrCurrProfileDepth, UsrCurrProfileVxi, UsrCurrProfileVyi, CurrVxi, CurrVyi )

      IMPLICIT NONE

      REAL(SiKi), INTENT(IN)                   :: QueryDepth
      REAL(SiKi), INTENT(IN), DIMENSION(:)     :: UsrCurrProfileDepth
      REAL(SiKi), INTENT(IN), DIMENSION(:)     :: UsrCurrProfileVxi
      REAL(SiKi), INTENT(IN), DIMENSION(:)     :: UsrCurrProfileVyi
      REAL(SiKi), INTENT(OUT)                  :: CurrVxi
      REAL(SiKi), INTENT(OUT)                  :: CurrVyi

      INTEGER(IntKi)                           :: I
      INTEGER(IntKi)                           :: NProfileRows
      REAL(SiKi)                               :: Frac

      NProfileRows = SIZE( UsrCurrProfileDepth )

      if ( QueryDepth >= UsrCurrProfileDepth(1) ) then
         CurrVxi = UsrCurrProfileVxi(1)
         CurrVyi = UsrCurrProfileVyi(1)
         return
      end if

      if ( QueryDepth <= UsrCurrProfileDepth(NProfileRows) ) then
         CurrVxi = UsrCurrProfileVxi(NProfileRows)
         CurrVyi = UsrCurrProfileVyi(NProfileRows)
         return
      end if

      do I = 1, NProfileRows - 1
         if ( QueryDepth >= UsrCurrProfileDepth(I+1) ) then
            Frac = ( QueryDepth - UsrCurrProfileDepth(I) ) / ( UsrCurrProfileDepth(I+1) - UsrCurrProfileDepth(I) )
            CurrVxi = UsrCurrProfileVxi(I) + Frac * ( UsrCurrProfileVxi(I+1) - UsrCurrProfileVxi(I) )
            CurrVyi = UsrCurrProfileVyi(I) + Frac * ( UsrCurrProfileVyi(I+1) - UsrCurrProfileVyi(I) )
            return
         end if
      end do

END SUBROUTINE CurrentProfileAtDepth
      
      
!----------------------------------------------------------------------------------------------------------------------------------
!> This routine computes the x and y current components for a given water elevation
SUBROUTINE Calc_Current( InitInp, z, h , DirRoot, CurrVxi, CurrVyi )
!----------------------------------------------------------------------------------------------------------------------------------

         ! This routine is used to initialize the variables associated with
         ! current.



      IMPLICIT                        NONE


         ! Passed Variables:

      REAL(SiKi),              INTENT(OUT) :: CurrVxi         !< xi-component of the current velocity at elevation z (m/s)
      REAL(SiKi),              INTENT(OUT) :: CurrVyi         !< yi-component of the current velocity at elevation z (m/s)

      REAL(SiKi),              INTENT(IN ) :: h               !< Effective water depth (meters)  This quantity must be positive-valued
      REAL(SiKi),              INTENT(IN ) :: z               !< Elevation relative to the mean sea level (meters)
      CHARACTER(*),            INTENT(IN ) :: DirRoot         !< The name of the root file including the full path to the current working directory.  
                                                              !! This may be useful if you want this routine to write a permanent record of what it does 
                                                              !! to be stored with the simulation results: the results should be stored in a file whose name 
                                                              !! (including path) is generated by appending any suitable extension to DirRoot.
      TYPE(Current_InitInputType), INTENT(IN ) :: InitInp     !< Initialization data for the current module 


         ! Local Variables:

      REAL(ReKi)                           :: CurrSSV         ! Magnitude of sub -surface current velocity at elevation z (m/s)
      REAL(ReKi)                           :: CurrNSV         ! Magnitude of near-surface current velocity at elevation z (m/s)



         ! If elevation z lies between the seabed and the mean sea level, compute the
         !   xi- and yi-components of the current (which depends on which current
         !   profile model is selected), else set CurrVxi and CurrVyi to zero:

      IF ( ( z < -h ) .OR. ( z > 0.0 ) )  THEN  ! .TRUE. if elevation z lies below the seabed or above mean sea level (exclusive)


            CurrVxi = 0.0  ! Set both the xi- and yi-direction
            CurrVyi = 0.0  ! current velocities to zero


      ELSE                                      ! Elevation z must lie between the seabed and the mean sea level (inclusive)


         SELECT CASE ( InitInp%CurrMod ) ! Which current profile model are we using?

         CASE ( 0 )              ! None!

            CurrVxi = 0.0  ! Set both the xi- and yi-direction
            CurrVyi = 0.0  ! current velocities to zero


         CASE ( 1 )              ! Standard (using inputs from PtfmFile).

            CurrSSV =      InitInp%CurrSSV0*( ( z + h                      )/h                      )**(1.0/7.0)
            CurrNSV = MAX( InitInp%CurrNSV0*( ( z + InitInp%CurrNSRef )/InitInp%CurrNSRef )           , 0.0_SiKi )

            CurrVxi = InitInp%CurrDIV*COS( D2R*InitInp%CurrDIDir ) + CurrSSV*COS( D2R*InitInp%CurrSSDir ) + &
                                   CurrNSV*COS( D2R*InitInp%CurrNSDir )

            CurrVyi = InitInp%CurrDIV*SIN( D2R*InitInp%CurrDIDir ) + CurrSSV*SIN( D2R*InitInp%CurrSSDir ) + &
                                   CurrNSV*SIN( D2R*InitInp%CurrNSDir )


         CASE ( 2 )              ! User-defined current profile model.

            CALL UserCurrent ( z, h, DirRoot, CurrVxi, CurrVyi )


         CASE ( 3 )              ! User-defined current profile from ASCII file.

            CALL CurrentProfileAtDepth( z, InitInp%UsrCurrProfileDepth, InitInp%UsrCurrProfileVxi, InitInp%UsrCurrProfileVyi, &
                                        CurrVxi, CurrVyi )

         ENDSELECT

      END IF

   RETURN
   
END SUBROUTINE Calc_Current


!----------------------------------------------------------------------------------------------------------------------------------
!> This routine is called at the start of the simulation to perform initialization steps. 
!! The parameters are set here and not changed during the simulation.
!! The initial states and initial guess for the input are defined.
SUBROUTINE Current_Init( InitInp, InitOut, ErrStat, ErrMsg )
!..................................................................................................................................

   TYPE(Current_InitInputType),       INTENT(INOUT)  :: InitInp     !< Input data for initialization routine
   TYPE(Current_InitOutputType),      INTENT(  OUT)  :: InitOut     !< Output for initialization routine
   INTEGER(IntKi),                    INTENT(  OUT)  :: ErrStat     !< Error status of the operation
   CHARACTER(*),                      INTENT(  OUT)  :: ErrMsg      !< Error message if ErrStat /= ErrID_None


     
      

      ! Local Variables:

   REAL(SiKi)                   :: CurrVxi                          ! xi-component of the current velocity at elevation z (m/s)     
   REAL(SiKi)                   :: CurrVyi                          ! yi-component of the current velocity at elevation z (m/s)
   REAL(SiKi)                   :: CurrVxi0                         ! xi-component of the current velocity at zi =  0.0 meters            (m/s)
   REAL(SiKi)                   :: CurrVyi0                         ! yi-component of the current velocity at zi =  0.0 meters            (m/s)
   REAL(SiKi)                   :: CurrVxiS                         ! xi-component of the current velocity at zi = -SmllNmbr meters       (m/s)
   REAL(SiKi)                   :: CurrVyiS                         ! yi-component of the current velocity at zi = -SmllNmbr meters       (m/s)
   REAL(SiKi), PARAMETER        :: SmllNmbr  = 9.999E-4             ! A small number representing epsilon for taking numerical derivatives.
   
   INTEGER                      :: I                                ! Generic index
      
      
      ! Initialize ErrStat
         
   ErrStat = ErrID_None         
   ErrMsg  = ""               

   IF ( InitInp%CurrMod == 3 ) THEN
      CALL ReadUsrCurrentProfile( TRIM(InitInp%CurrFile), InitInp, ErrStat, ErrMsg )
      IF ( ErrStat >= AbortErrLev ) RETURN
   END IF

      ! IF there are Morison elements, then compute the current components at each morison node elevation
      
   IF ( InitInp%NGridPts > 0 ) THEN    
         
      ALLOCATE ( InitOut%CurrVxi( InitInp%NGridPts ) , STAT=ErrStat )
      IF ( ErrStat /= ErrID_None )  THEN
         ErrMsg = ' Error allocating memory for the CurrVxi array.'
         ErrStat = ErrID_Fatal
         RETURN
      END IF
      
      ALLOCATE ( InitOut%CurrVyi( InitInp%NGridPts ) , STAT=ErrStat )
      IF ( ErrStat /= ErrID_None )  THEN
         ErrMsg = ' Error allocating memory for the CurrVyi array.'
         ErrStat = ErrID_Fatal
         RETURN
      END IF
      
      
         ! Loop over all of the points where current information is required
      
      DO I = 1, InitInp%NGridPts
         
         CALL Calc_Current( InitInp, InitInp%WaveKinGridzi(I), InitInp%EffWtrDpth, InitInp%DirRoot, CurrVxi, CurrVyi )        
         
         InitOut%CurrVxi(I) = CurrVxi
         InitOut%CurrVyi(I) = CurrVyi
       
      END DO     
     
   END IF   

      ! Compute the partial derivative for wave stretching
   CALL    Calc_Current( InitInp,  0.0_SiKi, InitInp%EffWtrDpth, InitInp%DirRoot, CurrVxi0, CurrVyi0 )
   CALL    Calc_Current( InitInp, -SmllNmbr, InitInp%EffWtrDpth, InitInp%DirRoot, CurrVxiS, CurrVyiS )

   InitOut%PCurrVxiPz0 = ( CurrVxi0 - CurrVxiS )/SmllNmbr                    ! xi-direction
   InitOut%PCurrVyiPz0 = ( CurrVyi0 - CurrVyiS )/SmllNmbr                    ! yi-direction
   
      ! Save the current velocity at the surface for wave-current modeling
   InitOut%CurrVxi0 = CurrVxi0
   InitOut%CurrVyi0 = CurrVyi0
   
END SUBROUTINE Current_Init

   
END MODULE Current
