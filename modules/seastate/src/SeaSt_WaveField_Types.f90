   call RegPack(RF, InData%WaveDir)
   call RegPack(RF, InData%WaveMultiDir)
   call RegPack(RF, InData%MCFD)
   call RegPack(RF, InData%WvLowCOff)
   call RegPack(RF, InData%WvHiCOff)
